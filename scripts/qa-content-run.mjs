// Runs the subject-independent content checks (scripts/qa-content.mjs) over every course's notes files and
// writes docs/qa/content-checks.md.
//   node scripts/qa-content-run.mjs     (also run by `npm run qa`)
// Hard failures (exit 1): text the page can't show as written. Lines a reviewer should look at are listed, not
// failed: the checks can find arithmetic that doesn't add up, but never whether the content is right.
import { readFile, readdir, writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";
import { escaping, notation, separatorInBrackets, numLine, numAnswerExplained, arithmetic, sourceUrl } from "./qa-content.mjs";
import { parseNotes } from "../kit/course/notes.js";

const ROOT = new URL("../", import.meta.url);
// statements that are correct in their context though the plain arithmetic disagrees, each with the reason
export const ALLOW = [
  { course: "maths", expr: "3 × 4 = 0", reason: "arithmetic in ℤ₁₂ (zero divisors)" },
];

export async function contentChecks() {
  const out = [];
  for (const slug of (await readdir(new URL("kit/courses/", ROOT))).sort()) {
    let files; try { files = (await readdir(new URL(`kit/courses/${slug}/notes/`, ROOT))).filter((f) => f.endsWith(".js")).sort(); } catch { continue; }
    const C = { slug, files: files.length, hard: [], review: { arithmetic: [], numWhy: [], url: [] }, counts: { lines: 0, num: 0 } };
    for (const f of files) {
      const url = new URL(`kit/courses/${slug}/notes/${f}`, ROOT), where = `${f.replace(".js", "")}`;
      const src = await readFile(url, "utf8");
      for (const e of escaping(src)) C.hard.push(`${where}:${e.line} single backslash is swallowed by JavaScript (write \\\\): "${e.text}"`);
      const text = (await import(pathToFileURL(url.pathname).href)).default;
      for (const line of String(text).split("\n")) {
        C.counts.lines++;
        if (notation(line)) C.hard.push(`${where}: ^{ or _{ not closed: "${line.slice(0, 80)}"`);
        if (separatorInBrackets(line)) C.hard.push(`${where}: " | " inside brackets splits the line (write " ∣ "): "${line.slice(0, 80)}"`);
        const n = numLine(line);
        if (n) { C.counts.num++; for (const p of n.problems) C.hard.push(`${where}: NUM ${p}: "${n.q.slice(0, 60)}"`); if (!n.problems.length && !numAnswerExplained(n)) C.review.numWhy.push(`${where}: answer ${n.ans} doesn't appear in the explanation of "${n.q.slice(0, 70)}"`); }
        for (const a of arithmetic(line)) if (!ALLOW.some((x) => x.course === slug && x.expr === a.expr)) C.review.arithmetic.push(`${where}: \`${a.expr}\`, but the left side is ${a.value}`);
      }
      for (const L of parseNotes(text)) for (const s of L.sources) if (!sourceUrl(s)) C.review.url.push(`${where} ${L.title}: source link isn't https: ${s.url}`);
    }
    out.push(C);
  }
  return out;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const res = await contentChecks();
  const today = new Date().toISOString().slice(0, 10);
  const md = ["# Content checks", "", `Generated by \`npm run qa\` on ${today} from \`scripts/qa-content.mjs\`.`, "",
    "These checks are mechanical. They find text that won't display as written (swallowed backslashes, unclosed `^{`, a field separator inside brackets, a numerical question the parser drops) and flag arithmetic that doesn't add up. They can't tell whether a lesson is mathematically, scientifically, legally or clinically right: every school still needs review by an expert.", "",
    "| Course | Notes files | Lines | NUM questions | Hard failures | Arithmetic to check | NUM explanations to check | Source links |", "|---|---|---|---|---|---|---|---|",
    ...res.map((c) => `| ${c.slug} | ${c.files} | ${c.counts.lines.toLocaleString("en-GB")} | ${c.counts.num} | ${c.hard.length} | ${c.review.arithmetic.length} | ${c.review.numWhy.length} | ${c.review.url.length} |`), ""];
  md.push("Allowed exceptions (correct in context):", "", ...ALLOW.map((a) => `- ${a.course}: \`${a.expr}\`: ${a.reason}`), "");
  for (const c of res) {
    const items = [...c.hard.map((x) => `- ❌ ${x}`), ...c.review.arithmetic.map((x) => `- 🔢 ${x}`), ...c.review.url.map((x) => `- 🔗 ${x}`), ...c.review.numWhy.map((x) => `- 🔍 ${x}`)];
    if (items.length) md.push(`## ${c.slug}`, "", ...items, "");
  }
  md.push("Key: ❌ hard failure; 🔢 arithmetic that doesn't add up as written; 🔗 a source link to check; 🔍 a numerical answer that its explanation doesn't show (often fine: a count, or an answer worded in the explanation), to check by eye.", "");
  await writeFile(new URL("docs/qa/content-checks.md", ROOT), md.join("\n"));
  for (const c of res) console.log(`content ${c.slug}: ${c.hard.length} hard, ${c.review.arithmetic.length} arithmetic, ${c.review.numWhy.length} NUM explanations, ${c.review.url.length} links to check`);
  const hard = res.flatMap((c) => c.hard.map((h) => `${c.slug} ${h}`));
  if (hard.length) { console.error(hard.join("\n")); process.exit(1); }
}
