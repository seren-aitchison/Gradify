// The pathways coverage report: which sites, subjects, qualifications and frameworks the curriculum navigation
// (explore.html#/pathways, kit/ui/pathways.js) reaches today, and where it's limited by missing registry data.
// Everything is counted from the graph (kit/curriculum/graph.js), so the report can't claim a link the pages don't show.
//   node scripts/curriculum/pathways-report.mjs        writes docs/curriculum/PATHWAYS-COVERAGE.md
//   node scripts/curriculum/pathways-report.mjs --check exits 1 if the file is out of date
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { buildGraph, subjectQualifications, bodyQualifications } from "../../kit/curriculum/graph.js";
import { GROUPS } from "../../kit/core/sites.js";

const root = new URL("../../", import.meta.url);
const catalogue = JSON.parse(readFileSync(new URL("kit/api/v1/catalogue.json", root), "utf8"));

export function report(g = buildGraph({ courses: catalogue.courses })) {
  const all = (kind) => [...g.nodes.values()].filter((n) => n.kind === kind);
  const count = (kind) => all(kind).length;
  const subjectsOfCourse = (c) => g.in(c, "taught-in").map((e) => g.get(e.from));
  const rows = (cells) => `| ${cells.join(" | ")} |`;
  const yes = (b) => (b ? "yes" : "–");

  const sites = GROUPS.flatMap((x) => x.items).map((s) => {
    const sid = [...g.nodes.values()].find((n) => n.kind === "site" && n.name === s.n)?.id, courses = sid ? g.in(sid, "on").map((e) => g.get(e.from)) : [];
    const subjects = [...new Set(courses.flatMap((c) => subjectsOfCourse(c.id)))], specs = subjects.flatMap((x) => g.out(x.id, "spec")), stages = courses.flatMap((c) => g.in(c.id, "course"));
    const awards = new Set(courses.flatMap((c) => g.out(c.id, "related-award").map((e) => e.to))), prof = [...awards].filter((a) => g.out(a, "set-by").length);
    return rows([s.n, courses.map((c) => c.name).join(", ") || "–", subjects.map((x) => x.name).join(", ") || (stages.length ? `stage: ${stages.map((e) => g.get(e.from).name).join(", ")}` : "–"), specs.length || "–", awards.size || "–", prof.length || "–"]);
  });
  const subjects = all("subject").sort((a, b) => a.name.localeCompare(b.name)).map((s) => {
    const q = subjectQualifications(g, s.key), courses = g.out(s.id, "taught-in"), related = g.out(s.id, "related"), awards = new Set(courses.flatMap((c) => g.out(c.to, "related-award").map((e) => e.to)));
    return rows([s.name, courses.length, q.map((x) => `${x.qualification.name} (${x.bodies.map((b) => b.name).join(", ")})`).join("; ") || "none in the registry", related.length, awards.size]);
  });
  const bodies = all("body").map((b) => rows([b.name, b.sub, bodyQualifications(g, b.key).map((x) => `${x.qualification.name}: ${x.specs.length}`).join(", ") || "–"]));
  const specs = all("spec").map((s) => rows([s.name, s.code || "–", yes(s.confirmed), s.statements === "imported" ? "yes" : "–", s.mastery ? `${s.mastery.points} points, ${g.out(s.id, "topic").length} topics` : "–"]));
  const countries = all("country").sort((a, b) => a.name.localeCompare(b.name)).map((c) => {
    const juris = g.out(c.id, "has").map((e) => g.get(e.to)), awards = juris.flatMap((j) => g.out(j.id, "offers").map((e) => g.get(e.to)));
    return rows([c.name, juris.length, awards.length, awards.filter((a) => a.type).length, awards.filter((a) => g.out(a.id, "related-course").some((e) => e.claim)).length]);
  });
  const orgs = all("org").map((o) => rows([o.name, g.out(o.id, "sets").map((e) => g.get(e.to).name).join("; "), g.out(o.id, "sets").flatMap((e) => g.out(e.to, "related-course").map((x) => `${g.get(x.to).name}${x.claim ? ` (${x.claim})` : ""}`)).join(", ") || "–"]));
  const stages = all("stage").map((s) => rows([s.name, g.out(s.id, "award").length, g.out(s.id, "course").map((e) => g.get(e.to).name).join(", ") || "–"]));

  return `# Pathways: curriculum navigation coverage

Generated by \`node scripts/curriculum/pathways-report.mjs\` from the curriculum graph (\`kit/curriculum/graph.js\`), which joins every registry: \`kit/curriculum/world.js\`, \`uk.js\`, \`coverage.js\`, \`subjects.js\`, \`kit/specs/\` and the course catalogue. A learner reaches all of it from Explore (\`explore.html#/pathways\`), in every direction. Nothing below is a coverage claim: "related" means a course covers subjects a qualification includes, and only a verified mapping means it covers the qualification itself.

## In numbers

| | |
|---|---|
| Countries | ${count("country") - 1} (and the international programmes) |
| Education systems | ${count("jurisdiction")} |
| Qualifications as countries name them | ${count("award")} |
| UK qualification types | ${count("qualification")} |
| Exam boards | ${count("body")} |
| Specifications | ${count("spec")} (${all("spec").filter((s) => s.mastery).length} mapped point by point) |
| Specification topics | ${count("topic")} |
| Professional bodies | ${count("org")} |
| Subjects | ${count("subject")} |
| Stages | ${count("stage")} |
| Gradify courses | ${count("course")} |
| Relationships | ${g.edges.length} |

## Sites

| Site | Courses | Subjects | Specifications | Related qualifications | Professional standards |
|---|---|---|---|---|---|
${sites.join("\n")}

## Subjects

| Subject | Courses | Qualifications and exam boards | Related subjects | Related qualifications |
|---|---|---|---|---|
${subjects.join("\n")}

## Exam boards

| Board | Where | Specifications in the registry |
|---|---|---|
${bodies.join("\n")}

## Specifications

| Specification | Code | Code and version checked | Statements imported | Mapped to lessons |
|---|---|---|---|---|
${specs.join("\n")}

## Countries

| Country | Education systems | Qualifications | Linked to a UK qualification type | With a coverage claim |
|---|---|---|---|---|
${countries.join("\n")}

## Professional bodies

| Body | Standards and qualifications | Gradify courses (claim) |
|---|---|---|
${orgs.join("\n")}

## Stages

| Stage | Qualifications | Gradify courses |
|---|---|---|
${stages.join("\n")}

## Limited by missing registry data

- **Specifications for every subject but Biology.** \`uk.js\` lists Biology's 21 UK specifications only, so subject → qualification → board works for Biology and every other subject shows "No specifications in the registry yet" with its Gradify course. Adding a subject's specifications to \`uk.js\` makes them appear everywhere, with no change to the pages.
- **Exam boards' other subjects.** A board shows only the specifications in the registry; each board page says it offers more.
- **One specification mapped to lessons** (AQA GCSE Biology 8461, paraphrased, not yet verified). Every other specification is listed, not mapped.
- **States, provinces and territories.** The United States, Canada and Australia are one system each in \`world.js\`; their state, provincial and territorial curricula aren't in the registry yet.
- **Year groups and key stages.** Stages are ISCED levels; year groups (Year 9, Grade 8) aren't in the registry yet.
- **Universities, programmes, modules and learning outcomes.** No institution registry exists. The undergraduate and postgraduate pages send learners to MyGradify to add their own course and modules.
- **Professional competencies.** Regulators and their standards are listed; individual competencies aren't in the registry yet.
- **Planned sites** (EconGradify, GeographyGradify) aren't in \`kit/core/sites.js\` yet, so they don't appear; they will once they're added there, with their courses.
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = new URL("docs/curriculum/PATHWAYS-COVERAGE.md", root), md = report();
  if (process.argv.includes("--check")) { const now = existsSync(out) ? readFileSync(out, "utf8") : ""; if (now !== md) { console.error("docs/curriculum/PATHWAYS-COVERAGE.md is out of date: run node scripts/curriculum/pathways-report.mjs"); process.exit(1); } console.log("pathways report up to date"); }
  else { writeFileSync(out, md); console.log("docs/curriculum/PATHWAYS-COVERAGE.md"); }
}
