#!/usr/bin/env node
// Specification Mastery's lesson links, generated from the mapping store (decision 6, owner, 25 Nov 2026). The view
// in kit/specs/<view>.js keeps what Gradify wrote by hand: point titles, its own summary of each point, flags, options
// and the lessons someone once listed (kept as `proposed`, never shown as coverage). Which lessons teach a point, and
// on what evidence, comes only from kit/curriculum/maps/<framework>.json, through kit/specs/<view>.links.js:
//   lessons, partial   the lessons that teach the point fully, or in part
//   evidence           "verified" when a named person checked every statement behind it, "ai-mapped" otherwise
//   state              full: every statement in the point is taught · partial: some are · none: every statement was
//                      checked and none is taught · unchecked: nothing taught, and some statements not checked yet
//   statements         how many of the point's statements are taught, out of how many
//
//   node scripts/curriculum/spec-view.mjs <view id>          write kit/specs/<view id>.links.js
//   node scripts/curriculum/spec-view.mjs <view id> --check  exit 1 if the committed file is out of date
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { loadIndex } from "./engine.mjs";
import { loadStore } from "../content/mapstore.mjs";
import { statusOf } from "../../kit/curriculum/mapping.js";

const root = new URL("../../", import.meta.url);
export const linksPath = (view) => new URL(`kit/specs/${view}.links.js`, root);
const TAUGHT = new Set(["covered", "partial", "mapped", "partially-mapped"]), FULL = new Set(["covered", "mapped"]), VERIFIED = new Set(["covered", "partial", "missing"]);

/** one point's links from its statements' rows: [{ status, link }] */
export function pointLinks(rows) {
  const taught = rows.filter((r) => TAUGHT.has(r.status));
  const lessonsOf = (rs, cov) => [...new Set(rs.flatMap((r) => (r.link.lessons || []).filter((l) => !cov || l.coverage === cov).map((l) => l.id)))];
  const all = taught.length === rows.length && rows.length > 0 && taught.every((r) => FULL.has(r.status));
  const lessons = all ? lessonsOf(taught, "full") : [];
  const partial = lessonsOf(taught).filter((id) => !lessons.includes(id));
  const decided = rows.every((r) => r.status !== "awaiting" || r.link?.status === "rejected");
  const state = all ? "full" : taught.length ? "partial" : decided && rows.length ? "none" : "unchecked";
  const evidence = !taught.length ? null : taught.every((r) => VERIFIED.has(r.status)) ? "verified" : "ai-mapped";
  return { lessons, partial, evidence, state, statements: { taught: taught.length, total: rows.length } };
}

/** every point of a view → its links, from the framework's index and store */
export function buildLinks(view, { index = loadIndex(view.framework), store = loadStore(view.framework) } = {}) {
  if (!index) throw new Error(`${view.framework} has no statement index`);
  const rows = index.statements.map((s) => ({ ref: s.ref, section: s.section, link: store.links?.[s.ref], status: statusOf(store.links?.[s.ref], index.version, store.specVersion, s.hash) }));
  const out = {};
  for (const t of view.topics) for (const g of t.groups) for (const p of g.points) {
    const own = rows.filter((r) => r.section === p.id);
    out[p.id] = pointLinks(own.length ? own : rows.filter((r) => r.ref.startsWith(`${p.id}.`)));
  }
  return out;
}

export const linksSource = (view, links) => `// Generated by node scripts/curriculum/spec-view.mjs ${view.id} from kit/curriculum/maps/${view.framework}.json. Don't edit by hand:
// a lesson is linked to a point only on a decision in the mapping store ("ai-mapped" until a named person verifies it).
export const LINKS = ${JSON.stringify(links, null, 1).replace(/\n\s*/g, " ")};
`;

if (import.meta.url === `file://${process.argv[1]}`) {
  const [id] = process.argv.slice(2), check = process.argv.includes("--check");
  if (!id) { console.log("usage: node scripts/curriculum/spec-view.mjs <view id> [--check]"); process.exit(1); }
  const view = (await import(new URL(`kit/specs/${id}.js`, root))).default;
  const src = linksSource(view, buildLinks(view)), f = linksPath(id), cur = existsSync(f) ? readFileSync(f, "utf8") : "";
  if (check) { if (cur !== src) { console.log(`${f.pathname} is out of date: run node scripts/curriculum/spec-view.mjs ${id}`); process.exit(1); } console.log("up to date"); }
  else { writeFileSync(f, src); const v = Object.values(buildLinks(view)), n = (k) => v.filter((x) => x.state === k).length; console.log(`${id}: ${v.length} points · ${n("full")} full · ${n("partial")} partial · ${n("none")} none · ${n("unchecked")} unchecked`); }
}
