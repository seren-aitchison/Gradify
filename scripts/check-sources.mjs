// Check the linked sources in a course's notes: every https link must load, and every DOI must exist in Crossref with a
// publication year matching the SRC line's date and a title that shares words with the citation. Writes a report to
// docs/qa/<slug>-source-check.md. A pass here checks that the reference exists and is described correctly; it is not a
// check of what the lesson says the source found (stage 4 of docs/CURRICULUM_QA.md still needs a human reader).
// Run: node scripts/check-sources.mjs psychology
import { readdir, writeFile } from "node:fs/promises";
import { parseNotes } from "../kit/course/notes.js";

const slug = process.argv[2]; if (!slug) { console.error("usage: node scripts/check-sources.mjs <course>"); process.exit(1); }
const dir = new URL(`../kit/courses/${slug}/notes/`, import.meta.url);
const files = (await readdir(dir)).filter((f) => /^u\d\d\.js$/.test(f)).sort();
const seen = new Map();
for (const f of files) for (const L of parseNotes((await import(new URL(f, dir))).default)) for (const s of L.sources) { if (!s.url) continue; const k = s.url; if (!seen.has(k)) seen.set(k, { ...s, lessons: [] }); seen.get(k).lessons.push(`${f.slice(0, 3)} ${L.title}`); }
const words = (t) => new Set(String(t).toLowerCase().replace(/<[^>]+>/g, "").match(/[a-z]{4,}/g) || []);
const rows = []; let bad = 0;
for (const [url, s] of seen) {
  let status = "", note = "";
  const doi = url.match(/^https:\/\/doi\.org\/(.+)$/)?.[1];
  try {
    if (doi) {
      const r = await fetch(`https://api.crossref.org/works/${encodeURIComponent(doi)}`, { headers: { "User-Agent": "Gradify source check (mailto:hello@getgradify.com)" } });
      if (!r.ok) { status = "✗"; note = `Crossref ${r.status}`; }
      else {
        const m = (await r.json()).message, year = (m.issued?.["date-parts"]?.[0]?.[0]) ?? (m.published?.["date-parts"]?.[0]?.[0]), title = String((m.title || [""])[0]).replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim();
        const tw = [...words(title)], need = Math.min(2, tw.length), overlap = tw.filter((w) => words(s.cite).has(w)).length, yearOk = String(year) === s.date.slice(0, 4);
        // older articles are often registered with the year they were digitised; accept them if volume and first page match
        const vp = s.cite.match(/(\d+)(?:\([^)]*\))?:([A-Za-z]?\d+)/), volPageOk = vp && String(m.volume) === vp[1] && String(m.page || "").split(/[-–]/)[0] === vp[2];
        status = (yearOk || volPageOk) && overlap >= need ? "✓" : "⚠"; note = `${title} (${year})${yearOk ? "" : volPageOk ? ` · Crossref dates the digitised record ${year}; volume and pages match the citation` : ` · year differs from ${s.date}`}${overlap >= need ? "" : " · title words don't match the citation"}`;
      }
    } else {
      const r = await fetch(url, { redirect: "follow", headers: { "User-Agent": "Mozilla/5.0 Gradify source check" } });
      status = r.ok ? "✓" : "✗"; note = `HTTP ${r.status}`;
    }
  } catch (e) { status = "✗"; note = String(e.message || e).slice(0, 80); }
  if (status !== "✓") bad++;
  rows.push(`| ${status} | ${s.cite.replace(/\|/g, "/")} | ${s.date} | ${url} | ${note.replace(/\|/g, "/")} |`);
  process.stdout.write(status);
}
const today = new Date().toISOString().slice(0, 10);
await writeFile(new URL(`../docs/qa/${slug}-source-check.md`, import.meta.url), [`# ${slug}: linked source check`, "", `Generated by \`node scripts/check-sources.mjs ${slug}\` on ${today}. ✓ = the link loads (web pages) or the DOI exists in Crossref with a matching year and title (articles). ⚠ = found, but the metadata differs from the citation: check by hand. ✗ = not found. Sources without a link (books, older works) are not checked here and remain on the citation register for human verification.`, "", `${seen.size} linked sources, ${seen.size - bad} passed.`, "", "| | Citation | Date | Link | Result |", "|---|---|---|---|---|", ...rows, ""].join("\n"));
console.log(`\n${seen.size} linked sources, ${bad} need attention → docs/qa/${slug}-source-check.md`);
