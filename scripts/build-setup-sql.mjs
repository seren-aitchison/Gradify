// One script that sets up a new, empty Gradify Supabase project in a single paste: every migration in
// supabase/migrations/, in date order, inside one transaction (all or nothing), each recorded in
// supabase_migrations.schema_migrations as scripts/supabase-admin.mjs and the Supabase CLI do, so neither tries to
// run them again later. Guide: docs/SUPABASE-CONNECT.md step 4.
//   node scripts/build-setup-sql.mjs           writes docs/setup/gradify-setup.sql
//   import { setupSql }                        used by tests/setup-sql.test.mjs
// The output refuses to run on a project that already has any of Gradify's tables, so it can't be run twice.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { listMigrations } from "./supabase-admin.mjs";

const lit = (x) => `'${String(x).replace(/'/g, "''")}'`;

export async function setupSql() {
  const list = await listMigrations();
  const parts = [
    `-- Gradify: set up a new Supabase project (generated by scripts/build-setup-sql.mjs; don't edit by hand).
-- Paste all of this into Supabase → SQL Editor → New query, then click Run. It takes a few seconds.
-- Contains ${list.length} migrations, ${list[0].version} to ${list.at(-1).version}. No keys, passwords or learner data.
-- All or nothing: if any part fails, nothing is changed.
begin;

do $$ begin
  if to_regclass('public.profiles') is not null or to_regclass('public.course_progress') is not null then
    raise exception 'Gradify''s tables already exist in this project, so nothing was changed. Run node scripts/verify-backend.mjs to see which migrations are missing.';
  end if;
end $$;

create schema if not exists supabase_migrations;
create table if not exists supabase_migrations.schema_migrations (version text primary key, statements text[], name text);`,
  ];
  for (const m of list) {
    const sql = (await readFile(m.url, "utf8")).trim();
    parts.push(`-- ===== ${m.file} =====\n${sql}\n\ninsert into supabase_migrations.schema_migrations (version, name, statements) values (${lit(m.version)}, ${lit(m.name)}, array[${lit(sql)}]);`);
  }
  parts.push("commit;\n");
  return parts.join("\n\n");
}

if (process.argv[1] && new URL(`file://${process.argv[1]}`).href === import.meta.url) {
  const out = new URL("../docs/setup/gradify-setup.sql", import.meta.url);
  await mkdir(new URL("./", out), { recursive: true });
  await writeFile(out, await setupSql());
  console.log("wrote docs/setup/gradify-setup.sql");
}
