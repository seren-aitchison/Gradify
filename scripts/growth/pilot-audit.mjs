// The lesson pages pilot (scripts/seo/lessons.mjs, /lessons/): page by page, what's strong and what's weak, and the
// evidence that decides when to add the next batch.
//   node scripts/growth/pilot-audit.mjs      write docs/growth/PILOT-AUDIT.md
// It reads the built pages and the lessons' notes; with Search Console data in data/growth/inputs/ it adds each page's
// impressions, clicks and position, and checks the scaling criteria.
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { PILOT } from "../seo/lessons.mjs";
import { lessonsOf, measure } from "./lesson-readiness.mjs";
import { gscRows } from "./sources.mjs";
import { pagesFrom } from "./report.mjs";
import { loadMap } from "../curriculum/engine.mjs";
import { specsFor } from "../../kit/curriculum/uk.js";

const root = new URL("../../", import.meta.url);
const read = (p) => readFileSync(new URL(p, root), "utf8");
const dec = (s) => String(s ?? "").replace(/&#39;/g, "'").replace(/&quot;/g, '"').replace(/&amp;/g, "&");

// Scale when the evidence says Google wants these pages, not after a fixed wait. All from Search Console.
export const CRITERIA = [
  ["indexed", "At least 70% of the pilot's indexable URLs are indexed (Indexing › Pages, filtered to the lessons sitemap)", (e) => e.indexedShare >= 0.7],
  ["impressions", "At least 40% of indexed pilot pages have had an impression", (e) => e.withImpressions >= 0.4],
  ["not-rejected", "Under 20% are 'Crawled – currently not indexed' (Google saw them and declined)", (e) => e.crawledNotIndexed < 0.2],
  ["quality", "No pilot page below the quality floor is indexable", (e) => e.belowFloorIndexable === 0],
];
/** whether to add the next batch, from the evidence (pure; missing evidence is never a pass) */
export function scaleDecision(e) {
  const rows = CRITERIA.map(([id, line, ok]) => ({ id, line, met: e[id === "indexed" ? "indexedShare" : id === "impressions" ? "withImpressions" : id === "not-rejected" ? "crawledNotIndexed" : "belowFloorIndexable"] == null ? null : ok(e) }));
  return { rows, go: rows.every((r) => r.met === true), waiting: rows.some((r) => r.met === null) };
}

export async function audit() {
  const lessons = (await lessonsOf(Object.keys(PILOT))).filter((x) => x.inPilot);
  // inbound links from every other built page in the main sections
  const inbound = new Map();
  for (const dir of ["topics", "questions", "exam-traps", "lessons", "features", "guides"]) {
    const walk = (d) => { for (const e of readdirSync(new URL(d, root), { withFileTypes: true })) { if (e.isDirectory()) walk(`${d}${e.name}/`); else if (e.name === "index.html") for (const m of read(`${d}${e.name}`).matchAll(/href="\/lessons\/([^/"]+\/[^/"]+)\//g)) if (`lessons/${m[1]}/` !== d) inbound.set(m[1], (inbound.get(m[1]) || 0) + 1); } };
    if (existsSync(new URL(`${dir}/`, root))) walk(`${dir}/`);
  }
  const gsc = pagesFrom(gscRows()), byPage = new Map(gsc.map((p) => [p.page, p]));
  const mapped = new Set(specsFor("biology").flatMap((s) => Object.entries(loadMap(s.id)?.links || {}).filter(([, l]) => l.status === "verified").flatMap(([, l]) => l.lessons.map((x) => x.id))));
  return lessons.map((x) => {
    const path = `lessons/${x.c.slug}/${x.id}/index.html`, h = existsSync(new URL(path, root)) ? read(path) : "";
    const head = h.split("</head>")[0], title = dec(head.match(/<title>([^<]*)/)?.[1]), m = measure(x.L), g = byPage.get(`/lessons/${x.c.slug}/${x.id}/`);
    const issues = [];
    if (!/<figure/.test(h)) issues.push("no diagram");
    if (x.L.mcq.filter((q) => q.why).length < 3) issues.push("fewer than 3 explained questions");
    if (m.missing.length) issues.push(`below the floor: ${m.missing.join("; ")}`);
    if ((inbound.get(`${x.c.slug}/${x.id}`) || 0) < 2) issues.push("fewer than 2 links in");
    if (!/Open this lesson in the course/.test(h)) issues.push("no way into the interactive lesson");
    if (!/assets\/og\/lessons\//.test(head)) issues.push("generic preview image");
    return { path, course: x.c.slug, id: x.id, title, noindex: /noindex/.test(head), floor: !m.missing.length, inbound: inbound.get(`${x.c.slug}/${x.id}`) || 0, mapped: x.c.slug === "biology" ? mapped.has(x.id) : null, gsc: g || null, issues };
  });
}

export function auditMd(rows, date) {
  const n = rows.length, count = (re) => rows.filter((r) => r.issues.some((i) => re.test(i))).length;
  const gscKnown = rows.some((r) => r.gsc);
  const ev = { indexedShare: null, withImpressions: gscKnown ? rows.filter((r) => r.gsc?.impressions > 0).length / n : null, crawledNotIndexed: null, belowFloorIndexable: rows.filter((r) => !r.floor && !r.noindex).length };
  const d = scaleDecision(ev);
  return `# Lesson pages pilot: audit

Generated by \`node scripts/growth/pilot-audit.mjs\` on ${date}. ${n} pilot lessons (${Object.entries(PILOT).map(([c, u]) => `${c} ${u.join(", ")}`).join("; ")}), at \`/lessons/<course>/<lesson>/\`. No competing URLs exist for these lessons.

## Headline

${Object.keys(PILOT).map((c) => { const rs = rows.filter((r) => r.course === c), below = rs.filter((r) => !r.floor).length; return `- **${c}**: ${rs.length - below} of ${rs.length} pages clear the quality floor`; }).join("\n")}

Read the pilot's Search Console results **per subject**. A subject whose pages are mostly below the floor (law unit 1 lacks worked examples, common mistakes and explained questions) may be left unindexed for reasons that say nothing about the others. Judging the whole pilot on the average would wrongly stall biology and chemistry. Improving law unit 1, or setting those pages \`noindex\` until improved, is the owner's call.

## What's strong

- Every title fits a search result (≤ 60 characters) and every description fits (≤ 155); ${rows.filter((r) => r.noindex).length} thin page is \`noindex\`.
- Every page renders the lesson with the app's own renderer, links into the interactive lesson, and cites its sources.
- ${rows.filter((r) => !r.issues.includes("generic preview image")).length} pages now have their own preview image (the lesson's diagram).

## What to improve, most valuable first

| Issue | Pages | Why it matters | Fix |
|---|---|---|---|
| Below the quality floor | ${count(/below the floor/)} | These are the pages Google is most likely to leave "Crawled – not indexed", which would slow the whole pilot | Add what each lacks (listed per page below): mostly explained practice questions |
| No diagram | ${count(/no diagram/)} | Diagrams are what image search and link previews show; text-only lessons look like every other result | Add the lesson's diagram where one exists in \`kit/diagrams\`; commission one for high-demand topics |
| Fewer than 3 explained questions | ${count(/explained questions/)} | Practice with explanations is the clearest difference from textbook pages (see COMPETITORS.md) | Write the missing explanations in the notes' MCQ blocks |
| Fewer than 2 links in | ${count(/links in/)} | Pages with few internal links are crawled and ranked less | Link from the unit's topic page, sibling lessons and related guides |
| Not mapped to a specification | ${rows.filter((r) => r.course === "biology").length} biology pages | Without a verified mapping the page can't say which exam statements it covers | The Biology mapping (\`docs/curriculum/README.md\`) |
| Titles say "Biology Lesson · SciGradify" | ${n} | "Lesson" and the brand carry no search intent; "explained", "notes" or the question students ask may earn more clicks | **Don't change yet.** Wait for 28 days of Search Console data, then test on the pages with impressions and low CTR, logged in \`data/growth/serp-changes.json\` |

## When to add the next batch

Scale on evidence, not on a timer: check Search Console from the first week (URL inspection on a sample of pilot pages shows indexing within days). Add the next batch (\`docs/growth/CONTENT-BACKLOG.md\`: 11 units, 281 pages) when all of these hold:

| Criterion | Status |
|---|---|
${d.rows.map((r) => `| ${r.line} | ${r.met === null ? "**unknown**: needs Search Console" : r.met ? "met" : "**not met**"} |`).join("\n")}

**Decision today:** ${d.go ? "add the next batch." : d.waiting ? "wait for Search Console data; meanwhile fix the pages below the floor, which is needed whatever the data says." : "improve the pilot before adding more."}

If Google indexes the pilot quickly, the next batch can follow within days. If most pages sit in "Crawled – currently not indexed", improve them first: more pages of the same kind won't fix that.

## Page by page

| Page | Title | Floor | Links in | Search (28 days) | Issues |
|---|---|---|---|---|---|
${rows.map((r) => `| /${r.path.replace(/index\.html$/, "")} | ${r.title.replace(/\|/g, "/")} | ${r.floor ? "yes" : "no"} | ${r.inbound} | ${r.gsc ? `${r.gsc.impressions} impr., ${r.gsc.clicks} clicks, pos. ${r.gsc.position?.toFixed(1)}` : "no data"} | ${r.issues.join("; ") || "none"} |`).join("\n")}
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const rows = await audit();
  writeFileSync(new URL("docs/growth/PILOT-AUDIT.md", root), auditMd(rows, new Date().toISOString().slice(0, 10)));
  console.log(`${rows.length} pilot pages audited; ${rows.filter((r) => r.issues.length).length} with something to improve.`);
}
