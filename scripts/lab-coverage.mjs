// Lab coverage for every Gradify course that has interactives: which lessons a lab serves (x.lessons), which
// lessons place it in their notes (IX: lines), and which links aren't placed yet. Subject-independent: it reads only
// the shared course contract (units, written, notes(unitId), interactives), so a new subject is covered by adding
// its course to kit/courses/. Writes docs/qa/lab-coverage.md; exits non-zero if a lesson embeds an unknown lab.
// Run: npm run labs   (also run by tests/lab-coverage.test.mjs)
import { readdir, writeFile, access } from "node:fs/promises";
import { parseNotes, norm } from "../kit/course/notes.js";

export async function labCoverage() {
  const out = [];
  for (const slug of (await readdir(new URL("../kit/courses/", import.meta.url))).sort()) {
    try { await access(new URL(`../kit/courses/${slug}/course.js`, import.meta.url)); } catch { continue; }
    const course = (await import(`../kit/courses/${slug}/course.js`)).default;
    const ixs = course.interactives || [];
    if (!ixs.length) continue;
    const ids = new Set(ixs.map((x) => x.id)), linked = new Map();
    for (const x of ixs) for (const l of x.lessons || []) linked.set(l, [...(linked.get(l) || []), x.id]);
    const placed = new Map(), unknown = [], lessons = [];
    for (const unit of course.units) {
      for (const l of unit.lessons) lessons.push({ ...l, unit: unit.id });
      if (!course.written.includes(unit.id)) continue;
      const byTitle = new Map(parseNotes(await course.notes(unit.id)).map((p) => [norm(p.title), p]));
      for (const l of unit.lessons) {
        const P = byTitle.get(norm(l.title)); if (!P) continue;
        const here = P.blocks.filter((b) => b.t === "ix").map((b) => b.id);
        if (here.length) placed.set(l.id, here);
        for (const id of here) if (!ids.has(id)) unknown.push(`${l.id} (${l.title}): IX: ${id}`);
      }
    }
    const notPlaced = [...linked].filter(([l, xs]) => xs.some((x) => !(placed.get(l) || []).includes(x)));
    out.push({ slug, name: course.name, total: lessons.length, labs: ixs.length, linked: linked.size, placed: placed.size,
      notPlaced: notPlaced.map(([l, xs]) => ({ l, title: lessons.find((x) => x.id === l)?.title, labs: xs.filter((x) => !(placed.get(l) || []).includes(x)) })), unknown });
  }
  return out;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const rows = await labCoverage(), pc = (a, b) => (b ? `${Math.round((100 * a) / b)}%` : "—");
  const doc = ["# Lab coverage", "", "Generated by `npm run labs` from each course's `interactives.js` and notes. A lab is *linked* to a lesson when it names the lesson in `lessons`; it is *placed* when the lesson's notes embed it with an `IX:` line at the point it's taught. Linked labs that aren't placed still appear at the end of the lesson (up to two), so *not placed* means less guided, not missing.", "",
    "| Course | Lessons | Labs | Lessons linked to a lab | Lessons with a placed lab | Linked but not placed |", "|---|---|---|---|---|---|",
    ...rows.map((r) => `| ${r.name} | ${r.total} | ${r.labs} | ${r.linked} (${pc(r.linked, r.total)}) | ${r.placed} (${pc(r.placed, r.total)}) | ${r.notPlaced.length} |`), ""];
  for (const r of rows) if (r.notPlaced.length || r.unknown.length) {
    doc.push(`## ${r.name}`, "");
    if (r.unknown.length) doc.push("**Unknown lab ids (fix these):**", ...r.unknown.map((u) => `- ${u}`), "");
    if (r.notPlaced.length) doc.push("Linked but not placed in the notes:", ...r.notPlaced.map((n) => `- ${n.l} ${n.title}: ${n.labs.join(", ")}`), "");
  }
  await writeFile(new URL("../docs/qa/lab-coverage.md", import.meta.url), doc.join("\n"));
  for (const r of rows) console.log(`${r.name}: ${r.placed}/${r.total} lessons place a lab, ${r.linked} linked, ${r.notPlaced.length} linked but not placed${r.unknown.length ? `, ${r.unknown.length} UNKNOWN` : ""}`);
  if (rows.some((r) => r.unknown.length)) process.exit(1);
}
