// Evidence: which passages of which sources support each knowledge item, and how much an item's wording overlaps
// any source it may not copy. Knowledge items are Gradify's own writing; this links each one to the passages a
// reviewer can read to check its facts, and measures that it isn't copied from a source whose licence forbids it.
// Writes data/knowledge/<subject>/evidence.json (ids, fingerprints and scores; no source text).
import { at, save, bm25, tokens, passagesOf, itemHash, longestSharedRun } from "./lib.mjs";

/** everything an item asserts, as text */
export const claimText = (k) => [k.title, k.text, ...(k.steps || []), ...(k.cases || []).flatMap((c) => [c.situation, c.outcome, c.why]), k.wrong ? `${k.right}` : "", k.equationNote, ...(k.terms || []).map((t) => `${t.term} ${t.definition}`)].filter(Boolean).join(" ");

/**
 * Evidence for each item from the sources it names: the best passages, and `support`, the share of the item's
 * distinctive words (weighted by rarity) that those passages contain. Overlap: the longest run of words the item
 * shares with any passage of a verify-only source.
 */
export function linkEvidence(items, sources, { top = 3 } = {}) {
  const pass = Object.values(sources).flatMap((s) => (passagesOf(s.id) || []).map((p) => ({ ...p, source: s.id, policy: s.policy })));
  const index = bm25(pass.map((p, i) => ({ id: i, text: p.text })));
  const out = {};
  for (const k of items) {
    const named = new Set(k.sources.map((s) => s.source)), text = claimText(k);
    const hits = index.search(text).filter((h) => named.has(pass[h.id].source)).slice(0, top);
    const want = [...new Set(tokens(text))], mass = want.reduce((m, w) => m + index.idf(w), 0) || 1;
    const covered = new Set(hits.flatMap((h) => h.matched));
    let worst = { words: 0, run: "", source: null, passage: null };
    for (const p of pass.filter((x) => x.policy === "verify-only")) { const r = longestSharedRun(text, p.text); if (r.words > worst.words) worst = { ...r, source: p.source, passage: p.id }; }
    out[k.id] = {
      itemHash: itemHash(k),
      support: Math.round((want.filter((w) => covered.has(w)).reduce((m, w) => m + index.idf(w), 0) / mass) * 100) / 100,
      passages: hits.map((h) => ({ source: pass[h.id].source, passage: pass[h.id].id, hash: pass[h.id].hash, score: h.score, matched: h.matched.slice(0, 10) })),
      missingFrom: [...named].filter((s) => !passagesOf(s)),
      overlap: { words: worst.words, source: worst.source, passage: worst.passage },
    };
  }
  return out;
}

export function writeEvidence(subject, items, sources) {
  const ev = linkEvidence(items, sources);
  save(at(`${subject}/evidence.json`), { subject, about: "Generated by scripts/knowledge/pipeline.mjs evidence: the source passages supporting each knowledge item (ids and fingerprints only), and the longest run of words each item shares with a source it may not copy.", items: ev });
  return ev;
}
