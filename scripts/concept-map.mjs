// Concept graph report for every course whose config has `concepts` (kit/learning/concepts.js):
//   node scripts/concept-map.mjs      (also run by `npm run qa`)
// writes docs/qa/<slug>-concepts.md: size, the sequencing findings (modules that need something taught later in
// the course), a school-level diagram, and each module's prerequisites. Exits 1 on an unknown reference or a cycle.
import { readdir, writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";
import { conceptGraph, validateGraph, graphStats, descendants } from "../kit/learning/concepts.js";

const ROOT = new URL("../", import.meta.url);
export async function conceptReports() {
  const out = [];
  for (const slug of (await readdir(new URL("kit/courses/", ROOT))).sort()) {
    let cfg; try { cfg = (await import(new URL(`kit/courses/${slug}/course.js`, ROOT).href)).default; } catch { continue; }
    if (!cfg?.concepts) continue;
    const g = conceptGraph(cfg.units, cfg.concepts);
    out.push({ slug, cfg, g, v: validateGraph(g), stats: graphStats(g) });
  }
  return out;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  let bad = 0;
  for (const { slug, cfg, g, v, stats } of await conceptReports()) {
    const U = cfg.unitWord || "Unit", unit = (id) => cfg.units.find((u) => u.id === id);
    const label = (k) => { const n = g.nodes.get(k), u = unit(n.unit); return `${n.module || u.title} (${U} ${u.n})`; };
    // school-level edges for the diagram
    const se = new Set();
    for (const [k, rs] of g.prereq) for (const r of rs) { const a = g.nodes.get(r).unit, b = g.nodes.get(k).unit; if (a !== b) se.add(`${a}>${b}`); }
    // the modules most depended on: weakness there puts the most at risk
    const hubs = [...g.nodes.keys()].map((k) => [k, descendants(g, k).length]).sort((a, b) => b[1] - a[1]).slice(0, 10);
    const md = [`# ${cfg.site}: concept graph`, "", `Generated by \`npm run qa\` from \`kit/courses/${slug}/concepts.js\` by the shared engine \`kit/learning/concepts.js\`. The graph says which modules each module builds on. The course uses it to show "Builds on" in every lesson and to flag a prerequisite when the learner's own answers show it's weak. Like the lessons, it awaits expert review.`, "",
      `| Modules | Prerequisite links | Lesson-level links | Starting points | Longest chain | Unknown references | Cycles |`, "|---|---|---|---|---|---|---|",
      `| ${stats.nodes} | ${stats.edges} | ${stats.lessonEdges} | ${stats.roots} | ${stats.longestChain} modules | ${v.unknown.length} | ${v.cycles.length} |`, ""];
    if (v.unknown.length) md.push("## Unknown references", "", ...v.unknown.map((x) => `- ❌ ${x}`), "");
    if (v.cycles.length) md.push("## Cycles", "", ...v.cycles.map((c) => `- ❌ ${c.map(label).join(" → ")}`), "");
    md.push("## Sequencing: prerequisites taught later", "", `Modules that build on something placed later in the course. Learners following the course in order meet these before their foundations: either the learner is pointed back (the "Builds on" links do this), or the order should change. ${v.forward.length} found.`, "",
      "| Module | Needs | |", "|---|---|---|", ...v.forward.map((f) => `| ${label(f.node)} | ${label(f.needs)} | ${((d) => d > 0 ? `${d} ${U.toLowerCase()}${d > 1 ? "s" : ""} later` : `later in the same ${U.toLowerCase()}`)(unit(g.nodes.get(f.needs).unit).n - unit(g.nodes.get(f.node).unit).n)} |`), "");
    md.push("## Most depended-on modules", "", "A weakness in these puts the most later modules at risk.", "", "| Module | Modules that build on it (directly or not) |", "|---|---|", ...hubs.map(([k, n]) => `| ${label(k)} | ${n} |`), "");
    md.push(`## ${U}-level map`, "", "```mermaid", "graph LR", ...cfg.units.map((u) => `  ${u.id}["${u.n}. ${u.title.replace(/"/g, "'")}"]`), ...[...se].sort().map((e) => `  ${e.replace(">", " --> ")}`), "```", "");
    md.push("## Every module's prerequisites", "", "| Module | Builds on |", "|---|---|", ...[...g.nodes.keys()].map((k) => `| ${label(k)} | ${[...g.prereq.get(k)].map(label).join("; ") || "(a starting point)"} |`), "");
    await writeFile(new URL(`docs/qa/${slug}-concepts.md`, ROOT), md.join("\n"));
    console.log(`${cfg.site}: concept graph ${stats.nodes} modules, ${stats.edges} links, ${v.forward.length} taught later, ${v.unknown.length} unknown, ${v.cycles.length} cycles`);
    bad += v.unknown.length + v.cycles.length;
  }
  if (bad) process.exit(1);
}
