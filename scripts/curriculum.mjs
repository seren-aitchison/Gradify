// The curriculum engine from the command line (kit/curriculum/engine.js over kit/curriculum/knowledge.js):
//   node scripts/curriculum.mjs                    validate, then write docs/qa/curriculum-knowledge.md (npm run curriculum)
//   node scripts/curriculum.mjs validate           validate only; exits 1 on any problem
//   node scripts/curriculum.mjs coverage <spec>    one specification's outcomes, e.g. aqa-8464
//   node scripts/curriculum.mjs impact <concept>   what a change to a concept affects, e.g. BIO-CELL-OSMOSIS-001
//   node scripts/curriculum.mjs hash <course>/<lesson>   a lesson's current content hash, for mappings/lessons.js
// Read-only except for the report: it never edits a lesson, a concept or a mapping.
import { readFile, writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";
import { lessonBlocks, hash } from "./curriculum-registry.mjs";
import { norm } from "../kit/core/text.js";
import { KB } from "../kit/curriculum/knowledge.js";
import { validate, coverage, impact, consistency, summary } from "../kit/curriculum/engine.js";
import { BAND_NAMES } from "../kit/curriculum/schema.js";

const ROOT = new URL("../", import.meta.url);

/** Map of "course/lessonId" → { course, id, title, hash, text } for every written lesson of the given courses. */
export async function loadLessons(slugs) {
  const out = new Map();
  for (const slug of [...new Set(slugs)].sort()) {
    const cfg = (await import(new URL(`kit/courses/${slug}/course.js`, ROOT).href)).default;
    for (const u of cfg.units.filter((u) => (cfg.written || []).includes(u.id))) {
      let src; try { src = await readFile(new URL(`kit/courses/${slug}/notes/${u.id}.js`, ROOT), "utf8"); } catch { continue; }
      const blocks = lessonBlocks(src);
      for (const l of u.lessons) { const text = blocks.get(norm(l.title)); if (text) out.set(`${slug}/${l.id}`, { course: slug, id: l.id, title: l.title, hash: hash(text), text }); }
    }
  }
  return out;
}
export const coursesIn = (kb) => [...kb.lessonMaps.map((b) => b.course), ...kb.pathways.map((p) => p.course)];

const STATUS = { covered: "✅ Covered", partial: "🟠 Partly covered", "above-level": "🟡 Taught above this level", "below-level": "🟠 Taught below this level", gap: "❌ Gap", "no-course": "⚪ No course offers this" };

export function report(kb, lessons) {
  const s = summary(kb, lessons), problems = validate(kb, lessons), findings = consistency(kb, lessons);
  const md = ["# Curriculum knowledge engine: coverage and quality", "",
    "Generated by `npm run curriculum` (scripts/curriculum.mjs) from `kit/curriculum/`. Nothing in it is a claim of verified coverage: every specification below is paraphrased and unchecked, and every concept awaits review, as the counts say. See docs/CURRICULUM-ARCHITECTURE.md.", "",
    "## At a glance", "", "| | |", "|---|---|",
    `| Subjects with canonical knowledge | ${s.subjects} |`,
    `| Canonical concepts | ${s.concepts} (verified ${s.conceptsByReview.verified}, reviewed ${s.conceptsByReview.reviewed}, awaiting review ${s.conceptsByReview.needs_review}, draft ${s.conceptsByReview.draft}) |`,
    `| Countries, education systems, stages | ${s.countries}, ${s.systems}, ${s.stages} |`,
    `| Specifications (awarding bodies; qualifications) | ${s.specifications} (${s.awardingBodies}; ${s.qualifications}), ${s.specificationsChecked} checked against the published document |`,
    `| Outcomes modelled, mapped to knowledge | ${s.outcomes}, ${s.outcomesMapped} |`,
    `| Outcomes covered at their level / partly / only above it / gaps / no course | ${s.outcomesCovered} / ${s.outcomesPartial} / ${s.outcomesAboveLevel} / ${s.outcomesGap} / ${s.outcomesNoCourse} |`,
    `| Lessons bound to knowledge (bindings) | ${s.lessonsBound} (${s.bindings}), ${s.bindingsCurrent} current, ${s.bindingsNeedReview} need review, ${s.bindingsConfirmed} confirmed by a named person |`,
    `| Sources cited, checked claim by claim | ${s.sources}, ${s.sourcesChecked} |`, "",
    "## Validation", "", problems.length ? problems.map((x) => `- ❌ ${x}`).join("\n") : "No problems: every reference resolves, there are no prerequisite cycles, and no claim is stronger than its evidence.", ""];
  md.push("## Coverage by specification", "");
  for (const sp of kb.specs) {
    const r = coverage(kb, sp.id, lessons);
    md.push(`### ${sp.body} ${sp.title}${sp.code ? ` (${sp.code})` : ""}`, "", `${BAND_NAMES[sp.band]}. ${sp.scope} ${sp.checked ? `Checked ${sp.checked.on} by ${sp.checked.by}.` : "Paraphrased; references not yet checked against the published specification."} Offered by: ${r.courses.length ? r.courses.join(", ") : "no Gradify course"}.`, "",
      "| Outcome | Status | Lessons | Note |", "|---|---|---|---|",
      ...r.outcomes.map((o) => `| ${o.outcome.ref ? `${o.outcome.ref} ` : ""}${o.outcome.title} | ${STATUS[o.status]} | ${o.lessons.join(", ") || "—"} | ${o.note || ""} |`), "");
  }
  md.push("## Concepts and their reach", "", "| Concept | Version | Review | Pathways | Lessons | Bindings needing review |", "|---|---|---|---|---|---|");
  for (const c of kb.concepts) {
    const im = impact(kb, c.id, lessons);
    md.push(`| ${c.id} ${c.title} | ${c.version} | ${c.review.status} | ${im.pathways.length} | ${im.lessons.length} | ${im.lessons.filter((l) => l.state !== "current").length} |`);
  }
  md.push("", "## Consistency findings", "", "Found mechanically. None is a factual error: these are gaps, editorial suggestions and curriculum-dependent points, for a reviewer to accept or reject. No lesson has been changed.", "",
    "| Lesson | Concept | Band | Class | Finding |", "|---|---|---|---|---|",
    ...findings.map((f) => `| ${f.course}/${f.lesson} ${f.title} | ${f.concept} | ${f.band} | ${f.severity} | ${f.kind === "terminology" ? `Uses "${f.term}" without "${f.prefer}". ${f.note}` : f.note} |`), "");
  return { md: md.join("\n"), problems, summary: s };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const [cmd = "report", arg] = process.argv.slice(2);
  const lessons = await loadLessons(coursesIn(KB));
  if (cmd === "hash") {
    const L = lessons.get(arg) || (await loadLessons([arg.split("/")[0]])).get(arg);
    if (!L) { console.error(`no written lesson ${arg}`); process.exit(1); }
    console.log(`${arg} ${L.title}: ${L.hash}`);
  } else if (cmd === "validate") {
    const p = validate(KB, lessons); p.forEach((x) => console.log(`❌ ${x}`));
    console.log(p.length ? `${p.length} problems` : "Knowledge base valid."); process.exit(p.length ? 1 : 0);
  } else if (cmd === "coverage") {
    const r = coverage(KB, arg, lessons);
    console.log(`${r.spec.body} ${r.spec.title}, offered by ${r.courses.join(", ") || "no course"}`);
    for (const o of r.outcomes) console.log(`  ${STATUS[o.status].padEnd(28)} ${o.outcome.id} ${o.outcome.title}${o.lessons.length ? ` ← ${o.lessons.join(", ")}` : ""}${o.note ? `\n      ${o.note}` : ""}`);
  } else if (cmd === "impact") {
    const im = impact(KB, arg, lessons);
    console.log(`${im.concept.id} ${im.concept.title}, version ${im.concept.version}`);
    console.log(`  needed by ${im.pathways.length} outcomes: ${[...new Set(im.pathways.map((p) => p.title))].join("; ")}`);
    console.log(`  builds into: ${im.dependents.join(", ") || "nothing yet"}`);
    for (const l of im.lessons) console.log(`  [${l.state}] ${l.course}/${l.lesson} (${l.role}, ${l.band}): ${l.action}${l.reasons.length ? `\n      ${l.reasons.join(" ")}` : ""}`);
  } else if (cmd === "report") {
    const { md, problems, summary: s } = report(KB, lessons);
    await writeFile(new URL("docs/qa/curriculum-knowledge.md", ROOT), md);
    console.log(`Curriculum knowledge: ${s.concepts} concepts, ${s.specifications} specifications, ${s.outcomes} outcomes (${s.outcomesCovered} covered at level, ${s.outcomesPartial} partly, ${s.outcomesAboveLevel} above, ${s.outcomesGap} gaps, ${s.outcomesNoCourse} no course), ${s.bindings} lesson bindings (${s.bindingsNeedReview} need review), ${problems.length} problems`);
    if (problems.length) { problems.forEach((x) => console.error(`❌ ${x}`)); process.exit(1); }
  } else { console.error(`unknown command ${cmd}`); process.exit(2); }
}
