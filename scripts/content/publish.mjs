// Publish-to-course: AI-checked and expert-reviewed drafts become lessons in their subject's course, through the
// rolling PR (merging it is the owner's approval). Each subject gets one published unit, "Specification lessons",
// with one module per topic, generated into two files:
//   kit/courses/<subject>/published.js   the unit's syllabus block, permanent lesson ids, blurb, track and QA record
//   kit/courses/<subject>/notes/uNN.js   the lessons, each with a TIER: label learners see
// The course files import published.js once (installHooks adds the import the first time), so the subject's own
// syllabus, ids and written list are never rewritten. Published ids are permanent: a lesson once published stays,
// in the last version that passed. Expert-required, gates-only and edited ("unchecked") drafts are never published.
import { drawnEnough, diagramsOf } from "./gates.mjs";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { at, out, fp, today, loadLedger } from "./lib.mjs";
import { splitUnit } from "./shorthand.mjs";
import { checkTiers } from "./report.mjs";
import { titleKey } from "../../kit/course/syllabus.js";

export const LABEL = { "ai-verified": "AI-checked", "expert-approved": "Expert-reviewed" };
const courseFile = (subject, f) => out(`kit/courses/${subject}/${f}`);
const literal = (s) => s.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
const lessonId = (uid, n) => `${uid}-${String(n).padStart(2, "0")}`;

async function current(subject) {
  const f = courseFile(subject, "published.js");
  if (!existsSync(f)) return {};
  return JSON.parse(readFileSync(f, "utf8").match(/export const PUBLISHED = (\{[\s\S]*\});\s*$/m)?.[1] || "{}");
}
/** the first unit number after the course's own units (read from its syllabus, without the published unit) */
function nextUnitNumber(subject) {
  const text = readFileSync(courseFile(subject, "syllabus.js"), "utf8");
  return Math.max(0, ...[...text.matchAll(/^(\d+)\. /gm)].map((m) => Number(m[1]))) + 1;
}

/**
 * Add the published unit's import to a course's syllabus, ids, course and QA files, once. Returns the files changed.
 * A course that doesn't have the expected shape is reported, not guessed at.
 */
export function installHooks(subject) {
  // each edit names the hook it must add; the import alone isn't enough, so a file without the expected shape is refused
  const changed = [], edit = (f, fn, hook) => { const u = courseFile(subject, f), s = readFileSync(u, "utf8"); if (s.includes("./published.js")) { if (!s.includes(hook)) throw new Error(`kit/courses/${subject}/${f}: imports published.js without its hook (${hook}), wire it by hand (see docs/CONTENT-ENGINE.md)`); return; } const t = fn(s); if (t === s || !t.includes(hook) || s.includes(hook)) throw new Error(`kit/courses/${subject}/${f}: unexpected shape, wire published.js by hand (see docs/CONTENT-ENGINE.md)`); writeFileSync(u, t); changed.push(f); };
  const imp = 'import { PUBLISHED } from "./published.js";   // lessons published by the content engine (scripts/content/publish.mjs)\n';
  const firstImport = (s) => s.replace(/^(import [^\n]+\n)/m, `$1${imp}`);
  if (!existsSync(courseFile(subject, "published.js"))) writeFileSync(courseFile(subject, "published.js"), publishedJs({}));
  edit("syllabus.js", (s) => firstImport(s)
    .replace(/export const UNITS = parseSyllabus\(SYLLABUS, IDS, RETIRED\);/, "export const UNITS = parseSyllabus(PUBLISHED.syllabus ? `${SYLLABUS.trim()}\\n${PUBLISHED.syllabus}` : SYLLABUS, IDS, RETIRED);\nfor (const u of UNITS) if (u.id === PUBLISHED.id) u.published = true;\nif (PUBLISHED.track) TRACKS.push(PUBLISHED.track);\nif (PUBLISHED.n) BLURBS[PUBLISHED.n] = PUBLISHED.blurb;"), "parseSyllabus(PUBLISHED.syllabus");
  edit("ids.js", (s) => `${imp}${s}`.replace(/\nexport const RETIRED/, "\nObject.assign(IDS, PUBLISHED.ids || {});\nexport const RETIRED"), "Object.assign(IDS, PUBLISHED.ids");
  edit("qa.js", (s) => `${imp}${s.trimEnd()}\nif (PUBLISHED.id) QA[PUBLISHED.id] = PUBLISHED.qa;\n`, "QA[PUBLISHED.id]");
  edit("course.js", (s) => firstImport(s).replace(/(\n\s*written: \[[^\]]*)\]/, "$1, ...(PUBLISHED.id ? [PUBLISHED.id] : [])]"), "...(PUBLISHED.id ? [PUBLISHED.id]");
  return changed;
}
const publishedJs = (P) => `// Generated by scripts/content/publish.mjs (gradify publish): the course's published unit. Don't edit by hand:
// lesson ids here are permanent (saved progress depends on them), and the next publish rewrites this file.
export const PUBLISHED = ${JSON.stringify(P, null, 1)};
`;

/** publish every eligible lesson of a subject; returns what was added or updated. preview (gradify preview, into a
 * scratch copy only): every filed lesson of the topic given, whatever its tier and whether its diagrams are drawn,
 * labelled "Preview" */
export async function publish(subject, { preview = false, topic = null } = {}) {
  checkTiers(subject);
  const led = loadLedger(subject), P = await current(subject), added = [], updated = [], skipped = [];
  const n = P.n || nextUnitNumber(subject), uid = P.id || `u${String(n).padStart(2, "0")}`;
  const ids = { ...(P.ids || {}) }, meta = { ...(P.lessons || {}) };
  const notesFile = courseFile(subject, `notes/${uid}.js`);
  const existing = existsSync(notesFile) ? splitUnit((await import(`${pathToFileURL(notesFile.pathname).href}?t=${Date.now()}`)).default) : [];
  // titles are identified as the syllabus parser identifies them (case and punctuation ignored), so two lessons can
  // never share an id there; texts are keyed by lesson id
  const byKey = new Map(Object.entries(ids).map(([id, t]) => [titleKey(t), id]));
  const texts = new Map(existing.map((l) => [byKey.get(titleKey(l.title)), l.text]).filter(([id]) => id));
  let next = Math.max(0, ...Object.keys(ids).map((id) => Number(id.slice(4)))) + 1;
  const claimed = new Set();   // ids given a lesson in this publish: a second lesson with the same title key waits for a rename
  for (const [topicId, e] of Object.entries(led.topics)) {
    if (topic && topicId !== topic) continue;
    const draft = e.file && out(e.file); if (!draft || !existsSync(draft)) continue;
    const lessons = new Map(splitUnit(readFileSync(draft, "utf8")).map((l) => [l.title, l.text]));
    for (const l of e.lessons || []) {
      const label = preview ? (l.superseded ? null : `Preview · ${LABEL[l.tier] || l.tier}`) : LABEL[l.tier]; if (!label) { skipped.push(`${l.title} (${l.tier})`); continue; }
      const text = lessons.get(l.title); if (!text || fp(text) !== l.hash) { skipped.push(`${l.title} (text changed since it was checked)`); continue; }
      // a DNEED: diagram counts towards filing, but a lesson is published only once its diagrams are drawn (config.standards)
      if (!preview && !drawnEnough(text)) { skipped.push(`${l.title} (its diagrams aren't all drawn yet: ${diagramsOf(text).needed.length} DNEED)`); continue; }
      const known = byKey.get(titleKey(l.title));
      // titles are unique in a unit: a second topic's lesson with the same title waits for a rename, and gets no id
      if (known && meta[known]?.topic && meta[known].topic !== topicId) { skipped.push(`${l.title} (${meta[known].topic} already published a lesson with this title)`); continue; }
      if (known && claimed.has(known)) { skipped.push(`${l.title} (another lesson in this publish has the same title)`); continue; }
      const id = known || lessonId(uid, next++), was = meta[id]; claimed.add(id);
      if (was?.hash === l.hash && was?.tier === label) continue;   // already published, unchanged
      ids[id] = l.title; byKey.set(titleKey(l.title), id);
      // every TIER: line in the draft goes; the only label is the one the ledger's tier gives
      const lines = text.split("\n").filter((x) => !/^\s*TIER:/.test(x));
      texts.set(id, [lines[0], `TIER: ${label}`, ...lines.slice(1)].join("\n"));
      meta[id] = { topic: topicId, module: e.title || topicId.split("/")[1], tier: label, hash: l.hash, reqs: l.reqs, publishedOn: today(), ...(l.approvedBy ? { approvedBy: l.approvedBy } : {}) };
      (was ? updated : added).push(`${id} ${l.title} · ${label}`);
    }
  }
  if (!Object.keys(ids).length) return { added, updated, skipped, unit: null };
  // module membership comes from each lesson's final record, so a lesson moved to another topic appears once
  const modules = new Map();
  for (const [id, m] of Object.entries(meta)) if (texts.has(id)) { if (!modules.has(m.module)) modules.set(m.module, []); modules.get(m.module).push(id); }
  const order = [...modules].map(([m, idsIn]) => ({ m, idsIn }));
  const syllabus = `${n}. Specification lessons\n${order.map(({ m, idsIn }) => `> ${m}\n${idsIn.map((id) => `* ${ids[id]}`).join("\n")}`).join("\n")}`;
  const next_P = {
    n, id: uid, title: "Specification lessons", syllabus, ids, lessons: meta,
    blurb: "Lessons written for exam-board specifications by Gradify's content engine and checked against cited sources. Each one says whether AI or a subject expert checked it.",
    track: { name: "Specification lessons", units: [n], from: "#64748b", to: "#0ea5a4" },
    qa: { standard: 3, reviewed: null, sources: null, signoff: null },
  };
  const body = order.flatMap(({ idsIn }) => idsIn.map((id) => texts.get(id))).join("\n\n");
  writeFileSync(notesFile, `// Specification lessons: generated by scripts/content/publish.mjs from the content engine's checked drafts
// (content/drafts/, content/ledger/${subject}.json). Each lesson's TIER: line is the label learners see. Edit the draft and
// run it back through the engine rather than editing here: the next publish replaces this file.
export default \`
${literal(body)}
\`;
`);
  writeFileSync(courseFile(subject, "published.js"), publishedJs(next_P));
  const hooks = installHooks(subject);
  return { added, updated, skipped, unit: uid, hooks };
}
