// Ecosystem inventory: what every Gradify site actually delivers, worked out from the code rather than from
// how its homepage looks, and a check that each site's release status (kit/core/sites.js) is justified.
//   node scripts/audit-sites.mjs           write docs/ECOSYSTEM-STATUS.md; exit 1 if a status isn't justified
//   import { inventory, statusProblems }   used by tests/sites-status.test.mjs
// It can only see the repository. Whether the backend is deployed, and whether pages have been checked in a
// real browser, are recorded separately (docs/BACKEND-STATUS.md, scripts/check-pages.cjs).
import { readdir, readFile, writeFile, access } from "node:fs/promises";
import { SITES, slugOf } from "../kit/core/site.js";
import { SUPABASE_URL, SUPABASE_ANON_KEY } from "../gradify.config.js";

const root = new URL("../", import.meta.url);
const exists = (p) => access(new URL(p, root)).then(() => true, () => false);

async function courses() {
  const out = [];
  for (const slug of await readdir(new URL("kit/courses/", root))) {
    const c = (await import(new URL(`kit/courses/${slug}/course.js`, root))).default;
    const lessons = c.units.reduce((a, u) => a + u.lessons.length, 0);
    const written = c.units.filter((u) => !c.written || c.written.includes(u.id)).reduce((a, u) => a + u.lessons.length, 0);
    const qa = c.qa ? Object.values(c.qa) : [];
    out.push({ slug, site: c.site, name: c.name, schools: c.units.length, lessons, written, interactives: (c.interactives || []).length, exams: (c.exams || []).length,
      reviewed: qa.filter((r) => r.reviewed).length, sourced: qa.filter((r) => r.sources).length, signedOff: qa.filter((r) => r.signoff).length, qaRecords: qa.length });
  }
  return out;
}

export async function inventory() {
  const all = await courses(), backend = Boolean(SUPABASE_URL && SUPABASE_ANON_KEY);
  const rows = [];
  for (const s of SITES) {
    const slug = slugOf(s), dir = `${slug}/`, built = Boolean(s.built) && (await exists(`${dir}index.html`));
    const cs = all.filter((c) => c.site === s.n);
    const lessons = cs.reduce((a, c) => a + c.lessons, 0), written = cs.reduce((a, c) => a + c.written, 0);
    // subject tools beyond the shared template: a course, or a dedicated tool page such as Body Intelligence
    const tools = [];
    for (const f of ["body.html"]) if (await exists(`${dir}${f}`)) tools.push(f.replace(".html", ""));
    rows.push({
      name: s.n, status: s.status, who: s.who, built, url: built ? `getgradify.com/${slug}/` : s.u || "",
      courses: cs.map((c) => c.name), lessons, written, coverage: lessons ? written / lessons : 0,
      interactives: cs.reduce((a, c) => a + c.interactives, 0), exams: cs.reduce((a, c) => a + c.exams, 0), tools,
      reviewed: cs.reduce((a, c) => a + c.reviewed, 0), signedOff: cs.reduce((a, c) => a + c.signedOff, 0), schools: cs.reduce((a, c) => a + c.schools, 0),
      engine: cs.length > 0, notesTools: built, persistent: backend ? "account (Supabase)" : "this browser only", ai: backend ? "configured, deployment unverified" : "scripted preview only",
    });
  }
  return { rows, courses: all, backend };
}

// what each status requires, so a polished homepage can never make a site "live"
export function statusProblems(rows) {
  const p = [];
  for (const r of rows) {
    if (r.status === "live" && !(r.written >= 300 && r.courses.length)) p.push(`${r.name} is "live" but has ${r.written} written lessons: live needs a usable course (300+ lessons written).`);
    if (r.status === "beta" && !(r.written > 0 || r.tools.length)) p.push(`${r.name} is "beta" but has no written lessons or subject tools.`);
    if (r.status === "soon" && (r.written >= 300)) p.push(`${r.name} is "coming soon" but has ${r.written} written lessons: consider beta or live.`);
    if (!["live", "beta", "soon", "development", "archived", "external"].includes(r.status)) p.push(`${r.name} has no valid status.`);
  }
  return p;
}

const pct = (x) => `${Math.round(x * 100)}%`;
async function write() {
  const { rows, courses: cs, backend } = await inventory(), probs = statusProblems(rows);
  const count = (st) => rows.filter((r) => r.status === st).length;
  const today = new Date().toISOString().slice(0, 10);
  const md = `# Gradify ecosystem status

Generated by \`node scripts/audit-sites.mjs\` on ${today}. Don't edit by hand: change \`kit/core/sites.js\` (status), the courses or \`gradify.config.js\`, then rerun.

**${rows.length} sites: ${count("live")} live, ${count("beta")} beta, ${count("soon")} coming soon, ${count("external")} external.** A site's status comes from what a learner can actually do there, never from how finished its homepage looks.

| Status | Meaning | Rule checked by this script |
|---|---|---|
| Live | A genuine, usable learning experience | A course with 300+ written lessons |
| Beta | Usable but substantially incomplete | Some written lessons, or a dedicated subject tool |
| Coming soon | Branded page plus the shared notes tools, no subject learning yet | Shown with a "coming soon" notice on its homepage |
| Development / Archived | Internal, or no longer maintained | |
| External | A separate product with its own site | |

## Shared infrastructure (applies to every site)

| | State | Evidence |
|---|---|---|
| Accounts and saved progress | **${backend ? "Configured in gradify.config.js; production test pending" : "Not connected: progress is saved in the learner's browser only"}** | \`gradify.config.js\` ${backend ? "has" : "has empty"} SUPABASE_URL and anon key; see docs/BACKEND-STATUS.md |
| AI | **${backend ? "Configured; the study-pack function's deployment is unverified" : "Scripted preview only"}** | The study-pack function is called at SUPABASE_URL/functions/v1/study-pack |
| Notes to flashcards | Works in the browser (built-in extractor) on every built site | kit/notes |

## Sites

| Site | Status | Course | Lessons written | Interactives | Exams | Subject tools | Reviewed schools | Expert sign-off |
|---|---|---|---|---|---|---|---|---|
${rows.map((r) => `| ${r.name} | ${r.status} | ${r.courses.join(", ") || "–"} | ${r.lessons ? `${r.written} / ${r.lessons} (${pct(r.coverage)})` : "–"} | ${r.interactives || "–"} | ${r.exams || "–"} | ${r.tools.join(", ") || "–"} | ${r.schools ? `${r.reviewed} / ${r.schools}` : "–"} | ${r.schools ? r.signedOff : "–"} |`).join("\n")}

## Courses

| Course | Site | Schools | Lessons written | Interactives | Reviewed | Sources checked | Signed off |
|---|---|---|---|---|---|---|---|
${cs.map((c) => `| ${c.name} | ${c.site} | ${c.schools} | ${c.written} / ${c.lessons} | ${c.interactives} | ${c.qaRecords ? c.reviewed : "no QA record"} | ${c.qaRecords ? c.sourced : "–"} | ${c.qaRecords ? c.signedOff : "–"} |`).join("\n")}

## Status checks

${probs.length ? probs.map((x) => `- ${x}`).join("\n") : "Every site's status is consistent with what it contains."}
`;
  await writeFile(new URL("docs/ECOSYSTEM-STATUS.md", root), md);
  console.log(`${rows.length} sites: ${count("live")} live, ${count("beta")} beta, ${count("soon")} soon. ${probs.length} status problems.`);
  for (const x of probs) console.log("  ", x);
  if (probs.length) process.exitCode = 1;
}
if (import.meta.url === `file://${process.argv[1]}`) await write();
