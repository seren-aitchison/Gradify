// scripts/write-doc.mjs: generated docs aren't rewritten just to change their date, so `npm test` leaves the tree clean.
import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { writeDoc, undated } from "../scripts/write-doc.mjs";

test("a generated doc is rewritten when its content changes, not when only its date does", async () => {
  const dir = await mkdtemp(join(tmpdir(), "write-doc-"));
  try {
    const url = pathToFileURL(join(dir, "doc.md"));
    assert.equal(await writeDoc(url, "Generated by `npm run qa` on 2026-11-16.\n\n| a | 1 |\n"), true, "a new file is written");
    assert.equal(await writeDoc(url, "Generated by `npm run qa` on 2026-11-18.\n\n| a | 1 |\n"), false, "only the date differs");
    assert.match(await readFile(url, "utf8"), /2026-11-16/);
    assert.equal(await writeDoc(url, "Generated by `npm run qa` on 2026-11-18 from x.\n\n| a | 2 |\n"), true, "the content differs");
    assert.match(await readFile(url, "utf8"), /2026-11-18 from x[\s\S]*\| a \| 2 \|/);
  } finally { await rm(dir, { recursive: true, force: true }); }
  assert.equal(undated("made on 2026-01-02. run on 2026-01-02 from"), "made on DATE. run on DATE from");
});
