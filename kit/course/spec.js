const BY = Object.fromEntries(FIELDS.map((f) => [f[0], f]));
const typeOf = (v) => (Array.isArray(v) ? arr : v === null ? "null" : typeof v);

/** Problems with a course config; an empty list means the shared engine can run it. */
export function checkCourse(cfg) {
  const p = [];
  if (!cfg || typeof cfg !== "object") return ["the config isn't an object"];
  for (const [name, type, required] of FIELDS) {
    if (cfg[name] === undefined) { if (required) p.push(`missing ${name}`); continue; }
    if (typeOf(cfg[name]) !== type) p.push(`${name} should be ${type === arr ? "an array" : `a ${type}`}, not ${typeOf(cfg[name])}`);
  }
  for (const k of Object.keys(cfg)) if (!BY[k]) p.push(`unknown field ${k} (a typo, or add it to kit/course/spec.js)`);
  if (!/^[a-z][a-z0-9-]*$/.test(String(cfg.slug))) p.push("slug should be lower case letters, digits and hyphens");
  // the syllabus: units and lessons with ids, no duplicates
  const unitIds = new Set(), lessonIds = new Set();
  (Array.isArray(cfg.units) ? cfg.units : []).forEach((u, i) => {
    if (!u?.id || !u.title || typeof u.n !== "number") p.push(`units[${i}] needs id, n and title`);
    if (unitIds.has(u?.id)) p.push(`duplicate unit id ${u.id}`); unitIds.add(u?.id);
    if (!Array.isArray(u?.lessons)) { p.push(`units[${i}] has no lessons array`); return; }
    u.lessons.forEach((l, j) => {
      if (!l?.id || !l.title) p.push(`units[${i}].lessons[${j}] needs id and title`);
      else if (lessonIds.has(l.id)) p.push(`duplicate lesson id ${l.id}`);
      lessonIds.add(l?.id);
    });
  });
  for (const id of Array.isArray(cfg.written) ? cfg.written : []) if (!unitIds.has(id)) p.push(`written names unit ${id}, which isn't in units`);
  const ns = new Set((cfg.units || []).map((u) => u.n));
  for (const key of ["tracks", "paths"]) for (const t of Array.isArray(cfg[key]) ? cfg[key] : []) for (const n of t.units || []) if (!ns.has(n)) p.push(`${key} "${t.name}" names unit ${n}, which doesn't exist`);
  if (cfg.levels && cfg.levels.length !== 3) p.push("levels should name exactly three difficulties");
  // labs: every lab can load and names real lessons; every evidence entry names a lab challenge's lesson that exists
  for (const x of Array.isArray(cfg.interactives) ? cfg.interactives : []) {
    if (!x.id || !x.title || typeof x.load !== fn) p.push(`interactive ${x.id || "?"} needs id, title and load()`);
    for (const lid of x.lessons || []) if (!lessonIds.has(lid)) p.push(`interactive ${x.id} names lesson ${lid}, which doesn't exist`);
  }
  for (const [lab, map] of Object.entries(cfg.evidence || {})) for (const [ch, lid] of Object.entries(map || {})) if (typeof lid === str && !lessonIds.has(lid)) p.push(`evidence ${lab}.${ch} names lesson ${lid}, which doesn't exist`);
  if (cfg.workspace && (!cfg.workspace.route || typeof cfg.workspace.engine !== fn)) p.push("workspace needs a route and engine()");
  if (cfg.concepts && typeof cfg.concepts.modules !== obj) p.push("concepts needs a modules object");
  return p;
}

// capability → the fields that switch it on (core, notes and questions are always on)
const CAPS = ["labs", "concepts", "workspace", "writing", "exams", "frameworks", "review", "authorities", "revalidation", "anatomy3d", "tutor"];
/** Which shared capabilities a config switches on. */
export function capabilitiesOf(cfg) {
  const on = new Set(["core", "notes", "questions", "mastery"]);
  for (const [name, , , cap] of FIELDS) if (CAPS.includes(cap) && cfg[name] != null && !(Array.isArray(cfg[name]) && !cfg[name].length)) on.add(cap);
  return [...on];
}
